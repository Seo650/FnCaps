@Suite struct EntryLanguageTests {
    private func decode(_ json: String) -> EntryLanguage? {
        try? JSONDecoder().decode(EntryLanguage.self, from: Data(json.utf8))
    }

    @Test func encodesAsStorageText() throws {
        let encoder = JSONEncoder()
        #expect(String(data: try encoder.encode(EntryLanguage.next), encoding: .utf8) == "\"next\"")
        #expect(String(data: try encoder.encode(EntryLanguage.last), encoding: .utf8) == "\"last\"")
        #expect(String(data: try encoder.encode(EntryLanguage.source("K")), encoding: .utf8) == "\"id:K\"")
        #expect(EntryLanguage.source("K").storageText == "id:K")
    }

    /// T-04.3-01: 모르는 값·빈 ID·숫자·null은 throw 없이 .next.
    @Test func decodesLeniently() {
        #expect(decode("\"next\"") == .next)
        #expect(decode("\"last\"") == .last)
        #expect(decode("\"id:K\"") == .source("K"))
        #expect(decode("\"id:\"") == .next)
        #expect(decode("\"foo\"") == .next)
        #expect(decode("7") == .next)
        #expect(decode("null") == .next)
    }

    @Test func mapsOutsideRule() {
        #expect(EntryLanguage(.last) == .last)
        #expect(EntryLanguage(.nextAfterLast) == .next)
    }

    @Test func choicesDefaultsAndSubscript() {
        var c = EntryChoices()
        #expect(c.caps == .next)
        #expect(c.fn == .next)
        c[.caps] = .last
        c[.fn] = .source("K")
        #expect(c.caps == .last)
        #expect(c.fn == .source("K"))
        #expect(EntryChoices.both(.last) == EntryChoices(caps: .last, fn: .last))
        #expect(EntryChoices(caps: .source("K"), fn: .last).storageText == "caps:id:K,fn:last")
    }

    @Test func ruleOnlyLowersSourceEntries() {
        let c = EntryChoices(caps: .source("K"), fn: .last)
        #expect(c.ruleOnly == EntryChoices(caps: .next, fn: .last))
        #expect(EntryChoices(caps: .next, fn: .next).ruleOnly == EntryChoices())
    }

    @Test func choicesJSONRoundTrip() throws {
        let original = EntryChoices(caps: .source("K"), fn: .last)
        let data = try JSONEncoder().encode(original)
        #expect(try JSONDecoder().decode(EntryChoices.self, from: data) == original)
        #expect(try JSONDecoder().decode(EntryChoices.self, from: Data(#"{"caps":"id:K"}"#.utf8))
                == EntryChoices(caps: .source("K"), fn: .next))
        #expect(try JSONDecoder().decode(EntryChoices.self, from: Data(#"{"caps":7}"#.utf8))
                == EntryChoices())
        #expect(try JSONDecoder().decode(EntryChoices.self, from: Data("{}".utf8))
                == EntryChoices())
    }
}

