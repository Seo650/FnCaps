@Suite struct ListSwitcherEntryTests {
    /// D-56: caps [영,한] 진입 한이면 밖(중·일)에서 Caps는 한으로, 안(한)에서는 다음(영)으로.
    @Test func capsEntryLanguageAppliesOutsideOnly() {
        let l = EFx.layout(caps: ["E", "K"], fn: ["J", "Z"],
                           entry: EntryChoices(caps: .source("K")))
        let outside = EFx.tracker(current: "J", lastCaps: "E", lastFn: "J")
        #expect(ListSwitcher.decide(.caps, current: "J", layout: l, tracker: outside) == .switchTo("K"))
        let inside = EFx.tracker(current: "K", previous: "E", lastCaps: "K", lastFn: "J")
        #expect(ListSwitcher.decide(.caps, current: "K", layout: l, tracker: inside) == .switchTo("E"))
    }

    /// D-56: fn [일,중] 진입 일이면 밖(영·한)에서 fn은 일로, 안(일)에서는 다음(중)으로.
    @Test func fnEntryLanguageAppliesOutsideOnly() {
        let l = EFx.layout(caps: ["E", "K"], fn: ["J", "Z"],
                           entry: EntryChoices(fn: .source("J")))
        #expect(ListSwitcher.decide(
            .fn, current: "E", layout: l,
            tracker: EFx.tracker(current: "E", lastCaps: "E", lastFn: "Z")) == .switchTo("J"))
        #expect(ListSwitcher.decide(
            .fn, current: "K", layout: l,
            tracker: EFx.tracker(current: "K", lastCaps: "K", lastFn: "Z")) == .switchTo("J"))
        #expect(ListSwitcher.decide(
            .fn, current: "J", layout: l,
            tracker: EFx.tracker(current: "J", previous: "Z", lastCaps: "E", lastFn: "J"))
            == .switchTo("Z"))
    }

    /// 진입 언어는 「쓰던 언어」보다 우선한다.
    @Test func entrySourceBeatsLastUsed() {
        let l = EFx.layout(caps: ["E", "K"], fn: [], entry: EntryChoices(caps: .source("K")))
        let t = EFx.tracker(current: "J", previous: "E", lastCaps: "E")
        #expect(ListSwitcher.decide(.caps, current: "J", layout: l, tracker: t) == .switchTo("K"))
    }

    /// D-09: 목록이 하나면 진입 값과 상관없이 그 소스로 간다.
    @Test func singleSourceListIgnoresEntry() {
        for entry in [EntryLanguage.next, .last, .source("K")] {
            let l = EFx.layout(caps: ["K"], fn: [], entry: EntryChoices(caps: entry))
            #expect(ListSwitcher.decide(.caps, current: "J", layout: l,
                                        tracker: EFx.tracker(current: "J")) == .switchTo("K"))
        }
    }

    /// D-10: 메뉴 막대·지정 단축키로 간 소스도 키의 목록 밖이면 진입 규칙을 따른다.
    @Test func currentAssignedSourceFollowsEntry() {
        let l = EFx.layout(caps: ["E", "K"], fn: [], assigned: ["R"],
                           entry: EntryChoices(caps: .source("K")))
        let t = EFx.tracker(current: "R", previous: "K", lastCaps: "K", lastAssigned: "R")
        #expect(ListSwitcher.decide(.caps, current: "R", layout: l, tracker: t) == .switchTo("K"))
    }

    /// D-11: 한 소스가 두 키에 있으면 누른 키의 목록 안/밖으로 판정한다.
    @Test func duplicatedSourceUsesPressedKeysList() {
        let l = EFx.layout(caps: ["E", "K"], fn: ["K", "J"],
                           entry: EntryChoices(caps: .source("K"), fn: .source("K")))
        #expect(ListSwitcher.decide(
            .caps, current: "K", layout: l,
            tracker: EFx.tracker(current: "K", previous: "E", lastCaps: "K")) == .switchTo("E"))
        #expect(ListSwitcher.decide(
            .fn, current: "K", layout: l,
            tracker: EFx.tracker(current: "K", previous: "J", lastFn: "K")) == .switchTo("J"))
        #expect(ListSwitcher.decide(
            .fn, current: "E", layout: l,
            tracker: EFx.tracker(current: "E", lastFn: "K")) == .switchTo("K"))
        #expect(ListSwitcher.decide(
            .caps, current: "J", layout: l,
            tracker: EFx.tracker(current: "J", lastCaps: "E")) == .switchTo("K"))
    }

    /// D-06 불변: 진입 값이 .source여도 현재가 목록 안이면 .next 규칙과 결과가 같다.
    @Test func insideBranchIgnoresEntry() {
        let entry = EFx.layout(caps: ["E", "K"], fn: ["J", "Z"],
                               entry: EntryChoices(caps: .source("K"), fn: .source("J")))
        let rule = KeyLayout(caps: ["E", "K"], fn: ["J", "Z"], sources: EFx.all, rule: .nextAfterLast)
        for current in ["E", "K"] {
            let t = EFx.tracker(current: current, lastCaps: current, lastFn: "J")
            #expect(ListSwitcher.decide(.caps, current: current, layout: entry, tracker: t)
                    == ListSwitcher.decide(.caps, current: current, layout: rule, tracker: t))
        }
        for current in ["J", "Z"] {
            let t = EFx.tracker(current: current, lastCaps: "E", lastFn: current)
            #expect(ListSwitcher.decide(.fn, current: current, layout: entry, tracker: t)
                    == ListSwitcher.decide(.fn, current: current, layout: rule, tracker: t))
        }
    }
}

