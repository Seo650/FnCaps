@Suite struct KeyLayoutEntryTests {
    @Test func keepsEntryForSourceInList() {
        let l = EFx.layout(caps: ["E", "K"], fn: ["J", "Z"],
                           entry: EntryChoices(caps: .source("K")))
        #expect(l.entry(for: .caps) == .source("K"))
        #expect(l.entry(for: .fn) == .next)
    }

    /// T-04.3-02: 목록에 없는 .source는 실행할 때만 .next로 낮춘다(저장값은 그대로).
    @Test func lowersEntrySourcesNotInList() {
        #expect(EFx.layout(caps: ["E", "K"], fn: [], entry: EntryChoices(caps: .source("ghost")))
                    .entry(for: .caps) == .next)
        // J는 fn 목록 소스다. Caps 진입으로는 쓸 수 없다.
        #expect(EFx.layout(caps: ["E", "K"], fn: ["J"], entry: EntryChoices(caps: .source("J")))
                    .entry(for: .caps) == .next)

        let stored = EntryChoices(caps: .source("ghost"))
        let l = EFx.layout(caps: ["E", "K"], fn: [], entry: stored)
        #expect(stored.caps == .source("ghost"))
        #expect(l.entry.caps == .next)
    }

    @Test func ruleConvenienceInitAppliesToBothKeys() {
        let l = KeyLayout(caps: ["E"], fn: ["K"], sources: EFx.all, rule: .last)
        #expect(l.entry(for: .caps) == .last)
        #expect(l.entry(for: .fn) == .last)
        #expect(KeyLayout.empty.entry == EntryChoices())
    }
}

