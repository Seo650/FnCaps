// D-01, D-09, D-10, D-11, 04.3: 키별 진입 언어. 「목록 밖에서 누를 때」 어디로 갈지의 단위 시험과
// 오라클 행(ListSwitcherEntryOracleTests)을 담는다.
//
// 아래 oracleRows는 key-list-sim.py의 press()·press_lists()에서 gen-oracle-entry.py가 만든 출력이다.
// 생성물이므로 손으로 고치지 않는다. 생성 스크립트는 개발 저장소에만 있다(공개 저장소에는 없음).
// 열: 구성 지정수 capsEntry|fnEntry cur prev lastC lastF lastA 키 도착 (None은 -, 지정 소스 누름은 S:ID)

/// 진입 언어 시험용 구성 도구. 언어 소스 E/K/J/Z에 지정 소스 R(ru)을 더한다.
private enum EFx {
    static let E = makeSource("E", ["en"])
    static let K = makeSource("K", ["ko"])
    static let J = makeSource("J", ["ja"])
    static let Z = makeSource("Z", ["zh-Hans"])
    static let R = makeSource("R", ["ru"])
    static let all: [SourceInfo] = [E, K, J, Z, R]

    static func layout(caps: [String], fn: [String], assigned: [String] = [],
                       entry: EntryChoices) -> KeyLayout {
        KeyLayout(caps: caps, fn: fn, assigned: assigned, sources: all, entry: entry)
    }

    /// 저장 문자열("next" | "last" | 소스 ID) -> 진입 언어.
    static func entry(_ raw: String) -> EntryLanguage {
        switch raw {
        case "next": return .next
        case "last": return .last
        default: return .source(raw)
        }
    }

    /// 오라클 구성 이름 -> (Caps 목록, fn 목록). gen-oracle-entry.py의 CFG와 같다.
    static func config(_ name: String) -> (caps: [String], fn: [String]) {
        switch name {
        case "c1f1": return (["E"], ["K"])
        case "c1f2": return (["E"], ["K", "J"])
        case "c2f1": return (["E", "K"], ["J"])
        case "c1f3": return (["E"], ["K", "J", "Z"])
        case "c2f2": return (["E", "K"], ["J", "Z"])
        case "c3f1": return (["E", "K", "J"], ["Z"])
        default: fatalError("unknown config \(name)")
        }
    }

    static func assigned(_ count: Int) -> [String] {
        switch count {
        case 0: return []
        case 1: return ["R"]
        default: fatalError("unknown assigned count \(count)")
        }
    }

    static func opt(_ s: String) -> SourceID? { s == "-" ? nil : s }

    static func tracker(current: SourceID?, previous: SourceID? = nil,
                        lastCaps: SourceID? = nil, lastFn: SourceID? = nil,
                        lastAssigned: SourceID? = nil) -> ListTracker {
        var t = ListTracker()
        t.setForTesting(current: current, previous: previous, lastCaps: lastCaps,
                        lastFn: lastFn, lastAssigned: lastAssigned)
        return t
    }
}

