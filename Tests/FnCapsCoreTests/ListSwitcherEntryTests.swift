private let entryOracleRowCount = 3892
private let entryOracleBundles = 110

@Suite struct ListSwitcherEntryOracleTests {
    private struct Row {
        let fields: [String]
        var name: String { fields[0] }
        var assignedCount: Int { Int(fields[1])! }
        var capsEntry: String { fields[2].split(separator: "|").map(String.init)[0] }
        var fnEntry: String { fields[2].split(separator: "|").map(String.init)[1] }
        var entryPair: String { fields[2] }
        var current: SourceID { fields[3] }
        var previous: SourceID? { EFx.opt(fields[4]) }
        var lastCaps: SourceID? { EFx.opt(fields[5]) }
        var lastFn: SourceID? { EFx.opt(fields[6]) }
        var lastAssigned: SourceID? { EFx.opt(fields[7]) }
        var key: String { fields[8] }
        var destination: SourceID { fields[9] }
    }

    private var rows: [Row] {
        entryOracleRows.split(separator: "\n").filter { !$0.isEmpty }.map {
            Row(fields: $0.split(separator: " ").map(String.init))
        }
    }

    @Test func rowCountAndBundles() {
        let rows = self.rows
        #expect(rows.count == entryOracleRowCount)
        #expect(rows.allSatisfy { $0.fields.count == 10 })
        let bundles = Set(rows.map { "\($0.name)|\($0.assignedCount)|\($0.entryPair)" })
        #expect(bundles.count == entryOracleBundles)
    }

    @Test func everyRowMatchesOracle() {
        for r in rows {
            let cfg = EFx.config(r.name)
            let layout = EFx.layout(
                caps: cfg.caps, fn: cfg.fn, assigned: EFx.assigned(r.assignedCount),
                entry: EntryChoices(caps: EFx.entry(r.capsEntry), fn: EFx.entry(r.fnEntry)))
            let tracker = EFx.tracker(current: r.current, previous: r.previous,
                                      lastCaps: r.lastCaps, lastFn: r.lastFn,
                                      lastAssigned: r.lastAssigned)
            let got: Decision
            let expected: Decision
            switch r.key {
            case "C":
                got = ListSwitcher.decide(.caps, current: r.current, layout: layout, tracker: tracker)
                expected = r.destination == r.current ? .noop : .switchTo(r.destination)
            case "F":
                got = ListSwitcher.decide(.fn, current: r.current, layout: layout, tracker: tracker)
                expected = r.destination == r.current ? .passThrough : .switchTo(r.destination)
            default:
                let target = String(r.key.dropFirst(2))   // "S:R"
                got = ListSwitcher.decideAssigned(target, current: r.current, layout: layout)
                expected = r.destination == r.current ? .noop : .switchTo(r.destination)
            }
            #expect(got == expected, "\(r.fields)")
        }
    }
}

