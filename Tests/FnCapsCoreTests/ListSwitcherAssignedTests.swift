/// 오라클·걸음 시험이 같이 쓰는 구성 도구. 언어 소스 E/K/J/Z에 지정 소스 R(ru)·V(vi)를 더한다.
private enum AFx {
    static let E = makeSource("E", ["en"])
    static let K = makeSource("K", ["ko"])
    static let J = makeSource("J", ["ja"])
    static let Z = makeSource("Z", ["zh-Hans"])
    static let R = makeSource("R", ["ru"])
    static let V = makeSource("V", ["vi"])
    static let all: [SourceInfo] = [E, K, J, Z, R, V]

    static func config(_ name: String) -> (caps: [String], fn: [String]) {
        switch name {
        case "c1f1": return (["E"], ["K"])
        case "c1f2": return (["E"], ["K", "J"])
        case "c2f1": return (["E", "K"], ["J"])
        case "c1f3": return (["E"], ["K", "J", "Z"])
        case "c2f2": return (["E", "K"], ["J", "Z"])
        case "c3f1": return (["E", "K", "J"], ["Z"])
        default: fatalError("unknown config \(name)")
        }
    }

    static func assigned(_ count: Int) -> [String] {
        switch count {
        case 0: return []
        case 1: return ["R"]
        case 2: return ["R", "V"]
        default: fatalError("unknown assigned count \(count)")
        }
    }

    static func layout(caps: [String], fn: [String], assigned: [String] = [],
                       rule: OutsideRule) -> KeyLayout {
        KeyLayout(caps: caps, fn: fn, assigned: assigned, sources: all, rule: rule)
    }

    static func rule(_ raw: String) -> OutsideRule { raw == "next" ? .nextAfterLast : .last }

    static func opt(_ s: String) -> SourceID? { s == "-" ? nil : s }

    static func tracker(current: SourceID?, previous: SourceID?, lastCaps: SourceID?,
                        lastFn: SourceID?, lastAssigned: SourceID? = nil) -> ListTracker {
        var t = ListTracker()
        t.setForTesting(current: current, previous: previous, lastCaps: lastCaps,
                        lastFn: lastFn, lastAssigned: lastAssigned)
        return t
    }
}

/// `SwitchPipeline`으로 실제 누름 경로(request → completed)를 밟는다.
private struct AssignedWalk {
    var pipeline = SwitchPipeline()
    let layout: KeyLayout

    init(layout: KeyLayout, current: SourceID) {
        self.layout = layout
        pipeline.seed(current: current, history: [], layout: layout)
    }

    var current: SourceID { pipeline.tracker.current! }

    @discardableResult
    mutating func press(_ key: TriggerKey) -> Decision {
        let (decision, request) = pipeline.press(key, actual: pipeline.tracker.current, layout: layout)
        if case .switchTo(let id) = decision, case let .start(_, run, _)? = request {
            _ = pipeline.completed(run: run, actual: id, layout: layout)
        }
        return decision
    }

    @discardableResult
    mutating func shortcut(_ target: SourceID) -> Decision {
        let decision = ListSwitcher.decideAssigned(target, current: current, layout: layout)
        guard case .switchTo(let id) = decision else { return decision }
        if case let .start(_, run, _) = pipeline.request(id, layout: layout) {
            _ = pipeline.completed(run: run, actual: id, layout: layout)
        }
        return decision
    }
}

